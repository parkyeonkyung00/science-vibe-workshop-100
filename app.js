function selectLessonCase(index) {
    lessonCaseTabs.forEach((_, i) => {
        const active = i === index;
        const button = document.getElementById('case-tab-' + i);
        button.setAttribute('aria-selected', String(active));
        button.tabIndex = active ? 0 : -1;
        document.getElementById('case-panel-' + i).hidden = !active;
        if (active) button.focus();
    });
}

function lessonCaseKey(event, index) {
    const target = { ArrowLeft: 1 - index, ArrowRight: 1 - index, Home: 0, End: 1 }[event.key];
    if (target === undefined) return;
    event.preventDefault();
    selectLessonCase(target);
}

