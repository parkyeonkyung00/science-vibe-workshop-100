let selectedRace = 0;

function raceTabPanel() {
    const { title } = raceTabs[selectedRace];
    const id = selectedRace ? 'subjectRace' + selectedRace : 'creationPrompt';
    return `<h2>${title}</h2>${prompt(id, 'ChatGPT에 붙여넣을 전체 프롬프트')}`;
}

function raceWorkshop() {
    const tabs = raceTabs.map(({ name }, i) => `<button type="button" role="tab" id="race-tab-${i}"
        aria-selected="${i === selectedRace}" aria-controls="race-panel"
        tabindex="${i === selectedRace ? 0 : -1}" onclick="selectRace(${i})"
        onkeydown="raceTabKey(event,${i})">${name}</button>`).join('');
    return `<div class="race-tabs" role="tablist" aria-label="교과별 레이스 프롬프트">${tabs}</div>
        <section id="race-panel" role="tabpanel" aria-labelledby="race-tab-${selectedRace}" tabindex="0">${raceTabPanel()}</section>`;
}

function selectRace(i) {
    selectedRace = i;
    document.querySelectorAll('.race-tabs [role="tab"]').forEach((tab, index) => {
        tab.setAttribute('aria-selected', String(index === i));
        tab.tabIndex = index === i ? 0 : -1;
    });
    const panel = document.querySelector('#race-panel');
    panel.setAttribute('aria-labelledby', 'race-tab-' + i);
    panel.innerHTML = raceTabPanel();
    document.querySelector('#race-tab-' + i).focus();
}

function raceTabKey(event, i) {
    const last = raceTabs.length - 1;
    const destinations = { ArrowLeft: i === 0 ? last : i - 1, ArrowRight: i === last ? 0 : i + 1, Home: 0, End: last };
    const target = destinations[event.key];
    if (target === undefined) return;
    event.preventDefault();
    selectRace(target);
}

